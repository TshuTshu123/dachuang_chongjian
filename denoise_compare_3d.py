"""Open3D 0.19.0: three synchronized, interactive 3D point-cloud windows.

Run from the VS Code terminal. Inputs are millimeters by default. RGB is retained;
voxel colors are averaged by Open3D. No Poisson or component removal is run.
All files generated by this script stay in its own project directory.
"""
import os
from pathlib import Path
ROOT = Path(__file__).resolve().parent
os.environ.setdefault('MPLCONFIGDIR', str(ROOT / '_work' / 'denoise_preview' / 'mpl'))
import argparse
import copy
import json
import sys
import time
import numpy as np
import open3d as o3d

from output_paths import latest_report

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

DEFAULT_INPUT = ROOT / 'export_00000.ply'


def parse_args():
    defaults = {'voxel': 0.003, 'outlier_neighbors': 20, 'outlier_std': 2.5}
    report = latest_report(ROOT)
    if report is not None:
        defaults.update(json.loads(report.read_text(encoding='utf-8')).get('settings', {}))
        print(f'Parameters from report: {report}', flush=True)
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('input', nargs='?', type=Path, default=DEFAULT_INPUT)
    p.add_argument('--input-unit', choices=['mm', 'm'], default='mm')
    p.add_argument('--voxel-mm', type=float, default=defaults['voxel'] * 1000,
                   help='Usually 2..5 mm, recommended 3; larger is faster with less detail.')
    p.add_argument('--neighbors', type=int, default=defaults['outlier_neighbors'],
                   help='Usually 15..40, recommended 20; >=3 required.')
    p.add_argument('--std', type=float, default=defaults['outlier_std'],
                   help='Usually 2..3, recommended 2.5; lower filters more aggressively.')
    p.add_argument('--point-size', type=float, default=2,
                   help='1..6 pixels, recommended 2; changes display only.')
    p.add_argument('--width', type=int, default=620, help='Width of each of the three windows.')
    p.add_argument('--height', type=int, default=860, help='Height of each window.')
    p.add_argument('--smoke-test', action='store_true', help=argparse.SUPPRESS)
    a = p.parse_args()
    if not a.input.is_file(): p.error(f'Input not found: {a.input}')
    if not np.isfinite([a.voxel_mm, a.std, a.point_size]).all(): p.error('Parameters must be finite')
    if a.voxel_mm <= 0 or a.std <= 0 or a.neighbors < 3: p.error('voxel-mm > 0, std > 0, neighbors >=3')
    if not 1 <= a.point_size <= 6: p.error('point-size must be 1..6 pixels')
    if a.width < 300 or a.height < 300: p.error('Window width/height must be >=300')
    return a


def prepare_clouds(a):
    started = time.perf_counter()
    raw = o3d.io.read_point_cloud(str(a.input))
    if not raw.has_points(): raise RuntimeError('Empty input point cloud')
    count = len(raw.points)
    raw.remove_non_finite_points()
    raw.remove_duplicated_points()
    raw.scale(0.001 if a.input_unit == 'mm' else 1, center=np.zeros(3))
    down = raw.voxel_down_sample(a.voxel_mm * 0.001)
    if len(down.points) <= a.neighbors: raise RuntimeError('Too few points; check units/voxel size')
    kept, indices = down.remove_statistical_outlier(nb_neighbors=a.neighbors, std_ratio=a.std)
    removed = down.select_by_index(indices, invert=True)
    if not kept.has_points(): raise RuntimeError('Filtering removed all points')
    origin = (raw.get_min_bound() + raw.get_max_bound()) / 2
    for cloud in [raw, down, kept, removed]: cloud.translate(-origin)
    gray = copy.deepcopy(kept).paint_uniform_color([0.60, 0.63, 0.68])
    red = copy.deepcopy(removed).paint_uniform_color([1, 0.03, 0.02])
    stats = {'original': count, 'finite_unique': len(raw.points), 'downsampled': len(down.points),
             'kept': len(kept.points), 'removed': len(removed.points),
             'preprocess_seconds': round(time.perf_counter() - started, 3)}
    print(json.dumps(stats, ensure_ascii=False, indent=2), flush=True)
    print(f'Voxel={a.voxel_mm:g} mm; SOR neighbors={a.neighbors}, std={a.std:g}', flush=True)
    print('Voxel reduction is resampling; red SOR flags are not noise ground truth.', flush=True)
    return {'raw': raw, 'down': down, 'kept': kept, 'gray': gray, 'red': red,
            'stats': stats, 'bounds': raw.get_axis_aligned_bounding_box()}


class SyncedViewer:
    def __init__(self, clouds, args):
        self.clouds, self.args = clouds, args
        self.views = []
        self.sync = True
        self.right_mode = 0
        self.point_size = args.point_size
        self.last_cameras = []
        titles = [f"原始彩色点云 | {len(clouds['raw'].points):,} 点",
                  f"{args.voxel_mm:g} mm 降采样 | {len(clouds['down'].points):,} 点",
                  f"去噪 / 红点诊断 | {len(clouds['kept'].points):,} 保留点 | M 切换"]
        try:
            for i, (name, title) in enumerate(zip(['raw', 'down', 'kept'], titles)):
                vis = o3d.visualization.VisualizerWithKeyCallback()
                if not vis.create_window(window_name=title, width=args.width, height=args.height,
                                         left=20 + i * (args.width + 12), top=40, visible=not args.smoke_test):
                    raise RuntimeError('OpenGL window creation failed; run in a local desktop session')
                self.views.append(vis)
                # Common bounds guarantee matching fit/clip planes in all windows.
                anchor = o3d.geometry.PointCloud(o3d.utility.Vector3dVector(
                    [clouds['bounds'].min_bound, clouds['bounds'].max_bound]))
                vis.add_geometry(anchor)
                vis.add_geometry(clouds[name])
                vis.remove_geometry(anchor, reset_bounding_box=False)
                options = vis.get_render_option()
                options.background_color = np.array([0.95, 0.96, 0.98])
                options.point_size = self.point_size
                options.light_on = False
                vis.register_key_callback(ord('R'), self.reset_callback)
                vis.register_key_callback(ord('S'), self.sync_callback)
                vis.register_key_callback(ord('M'), self.mode_callback)
                for key, mode in [('1', 0), ('2', 1), ('3', 2)]:
                    vis.register_key_callback(ord(key), self.make_mode_callback(mode))
                vis.register_key_callback(ord('='), self.bigger_callback)
                vis.register_key_callback(ord('-'), self.smaller_callback)
            self.reset_cameras()
        except Exception:
            self.close()
            raise

    def snapshots(self):
        result = []
        for vis in self.views:
            p = vis.get_view_control().convert_to_pinhole_camera_parameters()
            result.append(np.concatenate([p.extrinsic.ravel(), p.intrinsic.intrinsic_matrix.ravel()]).copy())
        return result

    def synchronize(self):
        now = self.snapshots()
        changed = [i for i in range(3) if not np.allclose(now[i], self.last_cameras[i], atol=1e-7)]
        if changed and self.sync:
            source = changed[0]
            p = self.views[source].get_view_control().convert_to_pinhole_camera_parameters()
            for i, vis in enumerate(self.views):
                if i != source and not vis.get_view_control().convert_from_pinhole_camera_parameters(p, allow_arbitrary=True):
                    raise RuntimeError('Camera synchronization failed')
            self.last_cameras = self.snapshots()
            return True
        self.last_cameras = now
        return False

    def reset_cameras(self):
        up = np.zeros(3)
        up_axis = int(np.argmax(self.clouds['bounds'].get_extent()))
        up[up_axis] = 1
        front = [0, -1, 0] if up_axis == 2 else [0, 0, -1]
        for vis in self.views:
            control = vis.get_view_control()
            control.set_up(up)
            control.set_front(front)
            control.set_lookat(self.clouds['bounds'].get_center())
            control.set_zoom(0.7)
        p = self.views[0].get_view_control().convert_to_pinhole_camera_parameters()
        for vis in self.views[1:]:
            if not vis.get_view_control().convert_from_pinhole_camera_parameters(p, allow_arbitrary=True):
                raise RuntimeError('Initial common camera could not be configured')
        self.last_cameras = self.snapshots()

    def set_mode(self, mode):
        self.right_mode = mode
        vis = self.views[2]
        vis.clear_geometries()
        names = [['kept'], ['gray', 'red'], ['red']][mode]
        for name in names:
            if self.clouds[name].has_points():
                vis.add_geometry(self.clouds[name], reset_bounding_box=False)
        print(['右栏：去噪后 RGB', '右栏：灰色保留点 + 红色删除点', '右栏：仅显示红色删除点'][mode], flush=True)

    def make_mode_callback(self, mode):
        def callback(vis):
            self.set_mode(mode)
            return False
        return callback

    def mode_callback(self, vis):
        self.set_mode((self.right_mode + 1) % 3)
        return False

    def reset_callback(self, vis):
        self.reset_cameras()
        return False

    def sync_callback(self, vis):
        self.sync = not self.sync
        self.last_cameras = self.snapshots()
        print('相机同步：' + ('开启' if self.sync else '关闭'), flush=True)
        return False

    def set_point_size(self, value):
        self.point_size = float(np.clip(value, 1, 6))
        for vis in self.views: vis.get_render_option().point_size = self.point_size
        print(f'显示点大小：{self.point_size:g} px', flush=True)

    def bigger_callback(self, vis):
        self.set_point_size(self.point_size + 0.5)
        return False

    def smaller_callback(self, vis):
        self.set_point_size(self.point_size - 0.5)
        return False

    def run(self):
        print('3D 对比已打开：左=原始，中=降采样，右=去噪。旋转/缩放/平移任意窗口，同步其余窗口。', flush=True)
        print('M 切换右栏；1 RGB，2 灰点+红点，3 仅红点；R 重置；S 同步开关；=/− 点大小；Q/Esc 关闭。', flush=True)
        while True:
            alive = True
            for vis in self.views:
                alive = vis.poll_events() and alive
            if not alive: break
            self.synchronize()
            for vis in self.views: vis.update_renderer()
            time.sleep(0.01)

    def smoke_test(self):
        out = ROOT / '_work' / 'denoise_3d_validation'
        out.mkdir(parents=True, exist_ok=True)
        self.views[1].get_view_control().rotate(85, 20)
        assert self.synchronize()
        states = self.snapshots()
        assert all(np.allclose(states[0], state, atol=1e-6) for state in states[1:])
        self.set_mode(1)
        self.set_mode(2)
        self.set_mode(0)
        self.set_point_size(2.5)
        self.reset_cameras()
        for i, vis in enumerate(self.views):
            vis.poll_events(); vis.update_renderer()
            vis.capture_screen_image(str(out / f'panel_{i + 1}.png'), do_render=True)
            image = o3d.io.read_image(str(out / f'panel_{i + 1}.png'))
            assert np.asarray(image).std() > 0
        self.set_mode(1)
        self.views[2].capture_screen_image(str(out / 'removed_overlay.png'), do_render=True)
        print('PASS: true 3D rendering, synchronized cameras, RGB, all removed-point modes, point size.', flush=True)
        print('Validation images:', out, flush=True)

    def close(self):
        for vis in self.views: vis.destroy_window()


def main():
    args = parse_args()
    clouds = prepare_clouds(args)
    viewer = SyncedViewer(clouds, args)
    try:
        if args.smoke_test: viewer.smoke_test()
        else: viewer.run()
    finally:
        viewer.close()


if __name__ == '__main__':
    main()
